<#
.SYNOPSIS
    Updates the KidTablet module on an already set-up tablet and applies it. Run as SYSTEM from ET Ducky.

.DESCRIPTION
    Writes the KidTablet module embedded below to Program Files (the previous copy is kept in
    C:\ProgramData\KidTablet\backup), then runs Sync-KidTablet. Sync rebuilds the home screen when
    its source changed, Edge policies, shortcuts and the kiosk profile. Apps, voice packs, her
    pictures, config.json and the child account are not touched.

    Generated by tools\Export-EtDuckyScripts.ps1 in KidTablet-setup. Edit the module there, not here.

    Exit code 0 on success, 1 on failure.
#>

# ---- Settings ---------------------------------------------------------------
$RestartSession = $true     # sign her out and back in so the new home screen starts now
# -----------------------------------------------------------------------------

$ErrorActionPreference = 'Stop'
try { Set-ExecutionPolicy Bypass -Scope Process -Force } catch { }

try {
    $principal = [Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
        throw 'Not elevated. Run as SYSTEM (leave "Run as logged in user" unchecked) or as an administrator.'
    }

    $moduleDir  = Join-Path $env:ProgramFiles 'WindowsPowerShell\Modules\KidTablet'
    $moduleFile = Join-Path $moduleDir 'KidTablet.psm1'
    if (-not (Test-Path $moduleFile)) { throw 'KidTablet is not installed on this device. Run Deploy-KidTablet.ps1 first.' }

    $backupDir = Join-Path $env:ProgramData 'KidTablet\backup'
    New-Item -ItemType Directory -Path $backupDir -Force | Out-Null
    $backup = Join-Path $backupDir ('KidTablet.psm1.{0}' -f (Get-Date -Format 'yyyyMMdd-HHmmss'))
    Copy-Item $moduleFile $backup -Force
    Write-Host "Previous module saved to $backup"

    $module = @'
__MODULE__
'@
    Set-Content -Path $moduleFile -Value $module -Encoding UTF8
    Write-Host ('Module written: {0}' -f (Get-FileHash $moduleFile).Hash)

    Import-Module $moduleFile -Force
    Sync-KidTablet -RestartSession:$RestartSession
    exit 0
} catch {
    Write-Error ("KidTablet update failed: {0}`r`nWhere: {1}" -f $_.Exception.Message, $_.ScriptStackTrace)
    exit 1
}
