<#
.SYNOPSIS
    Updates the Story Maker app on the tablet from the files embedded below. Run as SYSTEM from ET Ducky.

.DESCRIPTION
    Writes apps\story-maker\index.html and voices.js (embedded below as base64) into the package copy on the tablet
    (C:\KidTablet-new\KidTablet-setup), keeping the voice pack already injected into the installed
    index.html, then reinstalls the Story Maker app from it (Add-KidLocalApp), rewrites config.js
    from .env and syncs. The module is not changed; Update-KidTablet.ps1 does that, run it first if
    the module is older than 2026-10-07 (TTS_URL support).

    Generated by tools\Export-EtDuckyScripts.ps1 in KidTablet-setup. Edit the app there, not here.

    Exit code 0 on success, 1 on failure.
#>

# ---- Settings ---------------------------------------------------------------
$StageDir       = 'C:\KidTablet-new\KidTablet-setup'
$RestartSession = $false    # the app loads the new files on its next launch
# -----------------------------------------------------------------------------

$ErrorActionPreference = 'Stop'
try { Set-ExecutionPolicy Bypass -Scope Process -Force } catch { }

# The two files, base64 so ET Ducky's parameter scanner finds no tag-like tokens in the script.
$indexB64 = '__INDEX__'
$voicesB64 = '__VOICES__'
$index  = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($indexB64))
$voices = [Text.Encoding]::UTF8.GetString([Convert]::FromBase64String($voicesB64))

try {
    $moduleFile = Join-Path $env:ProgramFiles 'WindowsPowerShell\Modules\KidTablet\KidTablet.psm1'
    if (-not (Test-Path $moduleFile)) { throw 'KidTablet is not installed on this device. Run Deploy-KidTablet.ps1 first.' }
    if ((Get-Content -LiteralPath $moduleFile -Raw) -notmatch "TTS_URL") { throw 'The installed module predates TTS_URL support. Run Update-KidTablet.ps1 first.' }

    $appDir = Join-Path $StageDir 'apps\story-maker'
    New-Item -ItemType Directory -Path $appDir -Force | Out-Null
    $indexPath = Join-Path $appDir 'index.html'
    # Keep the voice pack (pre-rendered prompts) from the copy already here.
    $pack = $null
    if (Test-Path -LiteralPath $indexPath) {
        $m = [regex]::Match([IO.File]::ReadAllText($indexPath), ('<' + 'script id="voicepack">.*?<' + '/script>'), 'Singleline')
        if ($m.Success -and $m.Value -match 'window\.VOICE_PACK = \{') { $pack = $m.Value }
    }
    $new = $index
    if ($pack) {
        $m = [regex]::Match($new, ('<' + 'script id="voicepack">.*?<' + '/script>'), 'Singleline')
        if ($m.Success) { $new = $new.Substring(0, $m.Index) + $pack + $new.Substring($m.Index + $m.Length) }
    }
    $utf8 = New-Object Text.UTF8Encoding $false
    [IO.File]::WriteAllText($indexPath, $new, $utf8)
    [IO.File]::WriteAllText((Join-Path $appDir 'voices.js'), $voices, $utf8)
    Write-Host ('Story Maker files written' + $(if ($pack) { ' (voice pack kept, {0:N0} KB)' -f ($pack.Length / 1024) } else { ' (no voice pack on this tablet; Windows voice reads the menu prompts)' }))

    Import-Module $moduleFile -Force
    Add-KidLocalApp -Name 'Story Maker' -Path $appDir -NoSync
    $tile = Join-Path $StageDir 'apps\story-maker-tile.png'
    if (Test-Path $tile) { Set-KidApp -Name 'Story Maker' -Image $tile -Color '#5CD38B' }
    Update-KidAppConfig -Verbose
    Sync-KidTablet -RestartSession:$RestartSession
    Write-Host 'Story Maker updated.'
    exit 0
} catch {
    Write-Error ("Story Maker update failed: {0}`r`nWhere: {1}" -f $_.Exception.Message, $_.ScriptStackTrace)
    exit 1
}
